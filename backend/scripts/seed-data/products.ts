export function featuredPack(product: Product) {
  return product.packs.find((pack) => pack.size === product.featuredSize) ?? product.packs[0]
}

export function packBySize(product: Product, size: PackSize) {
  return product.packs.find((pack) => pack.size === size) ?? featuredPack(product)
}

export function getProduct(slug: string) {
  return products.find((product) => product.slug === slug)
}

export function categoryById(id: Product['category']) {
  return categories.find((category) => category.id === id)
}

export function relatedProducts(product: Product, count = 4) {
  const others = products.filter((item) => item.id !== product.id)
  const sameCategory = others.filter((item) => item.category === product.category)
  const rest = others.filter((item) => item.category !== product.category)
  return [...sameCategory, ...rest].slice(0, count)
}
